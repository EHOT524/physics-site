// Рисунок графика: mplot({ x: [-5, 5], y: [-5, 5], fns: [x => x * x], pts: [[1, 1]] })
function mplot(o) {
  var W = 340, H = Math.round(W * (o.y[1] - o.y[0]) / (o.x[1] - o.x[0]));
  if (H > 420) H = 420;
  var sx = function (x) { return (x - o.x[0]) / (o.x[1] - o.x[0]) * W; };
  var sy = function (y) { return H - (y - o.y[0]) / (o.y[1] - o.y[0]) * H; };
  var s = '<svg class="plot" viewBox="-4 -4 ' + (W + 8) + ' ' + (H + 8) + '" xmlns="http://www.w3.org/2000/svg">';
  var dx = o.stepX || 1, dy = o.stepY || 1, v;
  for (v = Math.ceil(o.x[0] / dx) * dx; v <= o.x[1]; v += dx) s += '<line x1="' + sx(v) + '" x2="' + sx(v) + '" y1="0" y2="' + H + '" stroke="currentColor" stroke-opacity=".13"/>';
  for (v = Math.ceil(o.y[0] / dy) * dy; v <= o.y[1]; v += dy) s += '<line y1="' + sy(v) + '" y2="' + sy(v) + '" x1="0" x2="' + W + '" stroke="currentColor" stroke-opacity=".13"/>';
  s += '<line x1="0" x2="' + W + '" y1="' + sy(0) + '" y2="' + sy(0) + '" stroke="currentColor"/><line y1="0" y2="' + H + '" x1="' + sx(0) + '" x2="' + sx(0) + '" stroke="currentColor"/>';
  s += '<text x="' + (W - 10) + '" y="' + (sy(0) - 5) + '" font-size="12" fill="currentColor">x</text><text x="' + (sx(0) + 5) + '" y="12" font-size="12" fill="currentColor">y</text>';
  s += '<text x="' + (sx(dx) - 3) + '" y="' + (sy(0) + 13) + '" font-size="11" fill="currentColor">' + dx + '</text><text x="' + (sx(0) - 12) + '" y="' + (sy(dy) + 4) + '" font-size="11" fill="currentColor">' + dy + '</text>';
  (o.fns || []).forEach(function (f) {
    var d = '', pen = false, N = 400, i;
    for (i = 0; i <= N; i++) {
      var x = o.x[0] + (o.x[1] - o.x[0]) * i / N, y = f(x);
      if (!isFinite(y) || y < o.y[0] - 1 || y > o.y[1] + 1) { pen = false; continue; }
      d += (pen ? 'L' : 'M') + sx(x).toFixed(1) + ' ' + sy(y).toFixed(1); pen = true;
    }
    s += '<path d="' + d + '" fill="none" stroke="var(--accent)" stroke-width="2"/>';
  });
  if (o.poly) s += '<polygon points="' + o.poly.map(function (p) { return sx(p[0]) + ',' + sy(p[1]); }).join(' ') + '" fill="var(--accent)" fill-opacity=".15" stroke="var(--accent)" stroke-width="2"/>';
  (o.pts || []).forEach(function (p) { s += '<circle cx="' + sx(p[0]) + '" cy="' + sy(p[1]) + '" r="3.5" fill="var(--accent)"/>'; });
  return s + '</svg>';
}

// Столбчатая диаграмма: mbars({ labels: ['янв'], values: [3], step: 2 })
function mbars(o) {
  var W = 340, H = 190, B = 22, L = 28, max = Math.max.apply(null, o.values), top = Math.ceil(max / o.step) * o.step;
  var n = o.values.length, bw = (W - L) / n, s = '<svg class="plot" viewBox="0 0 ' + W + ' ' + H + '" xmlns="http://www.w3.org/2000/svg">', v;
  for (v = 0; v <= top; v += o.step) {
    var y = H - B - v / top * (H - B - 8);
    s += '<line x1="' + L + '" x2="' + W + '" y1="' + y + '" y2="' + y + '" stroke="currentColor" stroke-opacity=".18"/><text x="' + (L - 4) + '" y="' + (y + 4) + '" font-size="10" text-anchor="end" fill="currentColor">' + v + '</text>';
  }
  o.values.forEach(function (val, i) {
    var h = val / top * (H - B - 8), x = L + i * bw;
    s += '<rect x="' + (x + bw * .18) + '" y="' + (H - B - h) + '" width="' + (bw * .64) + '" height="' + h + '" fill="var(--accent)"/><text x="' + (x + bw / 2) + '" y="' + (H - 7) + '" font-size="10" text-anchor="middle" fill="currentColor">' + o.labels[i] + '</text>';
  });
  return s + '</svg>';
}

